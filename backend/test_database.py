
# Import the function that prepares our SQLite database.
from database import initialize_database

# Import our support ticket functions.
# These functions should now use SQLite instead of dictionaries.
from tools import create_support_ticket, get_support_ticket


# STEP 1: Initialize our SQLite database.
# This creates the support_tickets table if necessary.
initialize_database()


# STEP 2: Create a fictional support ticket.
# The ticket should be stored permanently in spectrum.db.
result = create_support_ticket(
    customer_id="CUST001",
    issue="Internet disconnects every 10 minutes",
    priority="Medium"
)

# Display the creation result.
print("\nCREATION RESULT:")
print(result)


# STEP 3: Verify that ticket creation succeeded.
if result["status"] == "success":

    # Extract the ticket ID generated by SQLite.
    ticket_id = result["ticket"]["ticket_id"]

    # Retrieve the saved ticket using its ID.
    saved_ticket = get_support_ticket(ticket_id)

    # Display the retrieved information.
    print("\nLOOKUP RESULT:")
    print(saved_ticket)

    # Ensure we successfully retrieved the correct ticket.
    assert saved_ticket["status"] == "success"
    assert saved_ticket["ticket"]["customer_id"] == "CUST001"

    print("\nSUCCESS: SQLite ticket creation and retrieval work!")

else:
    # Display a message if ticket creation failed.
    print("\nFAILED: Could not create a support ticket.")
